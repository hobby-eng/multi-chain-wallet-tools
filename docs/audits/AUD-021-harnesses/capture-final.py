"""Capture source identity and compare independently generated public artifacts."""

import datetime
import hashlib
import json
import platform
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
EVIDENCE = ROOT / "docs/audits/AUD-021-evidence"


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def command(*args):
    return subprocess.check_output(args, cwd=ROOT, text=True).strip()


snapshot = json.loads((EVIDENCE / "snapshot.json").read_text())
changed = [name for name, expected in snapshot["files"].items()
           if not (ROOT / name).is_file() or digest(ROOT / name) != expected]
assert not changed, f"Reviewed files changed: {changed}"
assert command("git", "rev-parse", "HEAD") == snapshot["commit"]

canonical = EVIDENCE / "canonical-output/dist"
local = ROOT / "dist"
artifacts = {}
for edition in ("multi-chain-edition", "dash-community-edition"):
    # build:html updates tool pages; it does not replace an earlier release bundle.
    for tool in ("activity-viewer", "discovery-scanner", "key-derivation", "psbt-inspector"):
        paths = list((canonical / edition / tool).glob("*.html"))
        assert len(paths) == 1, (edition, tool)
        path = paths[0]
        relative = path.relative_to(canonical).as_posix()
        expected = digest(path)
        assert digest(local / relative) == expected, f"Artifact differs: {relative}"
        assert digest(canonical / edition / "release" / path.name) == expected
        artifacts[relative] = expected
assert len(artifacts) == 8

browser_reports = {}
for name in ("browser-files", "browser-regressions"):
    report_path = EVIDENCE / name / "report.json"
    report = json.loads(report_path.read_text())
    runs = report["runs"]
    assert all(row["passed"] for row in runs)
    for row in runs:
        if "sha256" in row:
            assert digest(Path(row["artifact"])) == row["sha256"]
        for path, expected in row.get("artifacts", {}).items():
            assert digest(Path(path)) == expected
    browser_reports[name] = {
        "passed": len(runs),
        "sha256": digest(report_path),
        "engines": sorted({row["browser"] + " " + row.get("version", row.get("browserVersion", ""))
                           for row in runs}),
    }
assert json.loads((EVIDENCE / "layout.json").read_text()) == []

rustsec = {}
for path in sorted(EVIDENCE.glob("rustsec-*.log")):
    match = re.search(r"\n(\{\"database\":.*\})\n", path.read_text())
    assert match, path
    result = json.loads(match[1])
    assert result["vulnerabilities"]["count"] == 0
    rustsec[path.stem] = {
        "database": result["database"],
        "dependencyCount": result["lockfile"]["dependency-count"],
        "vulnerabilities": 0,
        "warnings": {kind: [row["advisory"]["id"] + ": " + row["package"]["name"]
                            for row in rows] for kind, rows in result["warnings"].items()},
    }
assert len(rustsec) == 5

packages = {}
for name in ("typescript", "vitest", "prettier", "playwright"):
    packages[name] = json.loads((ROOT / "node_modules" / name / "package.json").read_text())["version"]
dockerfile = (ROOT / "Dockerfile.reproducible").read_text()
environment = {
    "os": platform.platform(),
    "node": command(str(Path.home() / ".local/bin/node"), "--version"),
    "packageManager": json.loads((ROOT / "package.json").read_text())["packageManager"],
    "packages": packages,
    "docker": command("docker", "--version"),
    "canonicalRust": re.search(r"--default-toolchain ([0-9.]+)", dockerfile)[1],
    "canonicalWasmBindgen": "0.2.129",
    "poppler": "Existing host pdftotext used for the separately recorded printed-card test.",
    "rustsecDatabase": rustsec["rustsec-dash"]["database"],
}
summary = {
    "capturedAt": datetime.datetime.now(datetime.timezone.utc).isoformat(),
    "commit": snapshot["commit"],
    "tree": snapshot["tree"],
    "trackedFilesUnchanged": len(snapshot["files"]),
    "trackedFileManifestSha256": hashlib.sha256(
        json.dumps(snapshot["files"], sort_keys=True, separators=(",", ":")).encode()).hexdigest(),
    "artifactRelationship": "Eight fresh uncached canonical artifacts match native HTML bytes and browser-test hashes.",
    "releaseRelationship": "Canonical flat release copies match their fresh tool pages. Existing native dist release folders were not regenerated by build:html and are not approved by this review.",
    "artifacts": artifacts,
    "browserReports": browser_reports,
    "rustsec": rustsec,
    "environment": environment,
    "manuallyViewedScreenshots": [
        "browser-files/chromium-multi-chain-key-derivation-390.png",
        "browser-files/firefox-dash-community-activity-viewer-1280.png",
        "browser-files/chromium-multi-chain-discovery-scanner-1280.png",
        "browser-files/chromium-dash-community-psbt-inspector-390.png",
    ],
    "screenshotAssessment": "Representative mobile/desktop screenshots showed no new clipped controls, overlap or horizontal overflow; automated layout also returned no findings.",
}
(EVIDENCE / "final-snapshot.json").write_text(json.dumps(summary, indent=2) + "\n")
print(f"PASS: {len(snapshot['files'])} reviewed tracked files unchanged; 8 canonical/native HTML hashes match; browser hashes match; 5 RustSec lockfiles have no vulnerability advisory.")
