import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const CANONICAL_WASM_BINDGEN_VERSION = '0.2.128';

function readUleb(bytes, state) {
  let value = 0;
  let shift = 0;
  for (let count = 0; count < 5; count += 1) {
    if (state.offset >= bytes.length) throw new Error('Truncated WASM producers section.');
    const byte = bytes[state.offset++];
    value |= (byte & 0x7f) << shift;
    if ((byte & 0x80) === 0) return value >>> 0;
    shift += 7;
  }
  throw new Error('Invalid ULEB128 value in WASM producers section.');
}

function readString(bytes, state) {
  const length = readUleb(bytes, state);
  const end = state.offset + length;
  if (end > bytes.length) throw new Error('Truncated string in WASM producers section.');
  const value = new TextDecoder('utf-8', { fatal: true }).decode(bytes.subarray(state.offset, end));
  state.offset = end;
  return value;
}

export function readWasmProducers(bytes) {
  const module = new WebAssembly.Module(bytes);
  const sections = WebAssembly.Module.customSections(module, 'producers');
  if (sections.length !== 1) {
    throw new Error(`Expected exactly one WASM producers section; found ${sections.length}.`);
  }
  const payload = new Uint8Array(sections[0]);
  const state = { offset: 0 };
  const fields = new Map();
  const fieldCount = readUleb(payload, state);
  for (let fieldIndex = 0; fieldIndex < fieldCount; fieldIndex += 1) {
    const fieldName = readString(payload, state);
    const valueCount = readUleb(payload, state);
    const values = new Map();
    for (let valueIndex = 0; valueIndex < valueCount; valueIndex += 1) {
      values.set(readString(payload, state), readString(payload, state));
    }
    fields.set(fieldName, values);
  }
  if (state.offset !== payload.length) throw new Error('Trailing bytes in WASM producers section.');
  return fields;
}

export function assertCanonicalWasmBindgenProducer(bytes, label = 'WASM module') {
  const actual = readWasmProducers(bytes).get('processed-by')?.get('wasm-bindgen');
  if (actual !== CANONICAL_WASM_BINDGEN_VERSION) {
    throw new Error(
      `${label} must be generated by crates.io wasm-bindgen ${CANONICAL_WASM_BINDGEN_VERSION}; found ${actual ?? 'no wasm-bindgen producer'}.`,
    );
  }
}

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const modules = [
  ['Dash Orchard WASM', 'packages/dash-shielded-wasm/generated/dash_shielded_wasm_bg.wasm'],
  ['Shamir WASM', 'packages/recovery-shamir-wasm/generated/recovery_shamir_wasm_bg.wasm'],
  ['Codex32 WASM', 'packages/recovery-codex32-wasm/generated/recovery_codex32_wasm_bg.wasm'],
];

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const [label, relativePath] of modules) {
    assertCanonicalWasmBindgenProducer(readFileSync(resolve(root, relativePath)), label);
  }
  console.log(`Verified canonical wasm-bindgen producer metadata for ${modules.length} WASM modules.`);
}
