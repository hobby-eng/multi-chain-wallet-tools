// Writes the Deriver's NFKD tables (packages/crypto-core/src/unicode-nfkd-data.ts) from Unicode
// 18.0.0's UnicodeData.txt (test/fixtures/unicode18), so that a BIP39 passphrase is normalized by
// the version that MHFE's specification pins, whatever version the browser carries. The tables are
// UnicodeData's own fields, transcribed: each decomposition mapping (field 5) without its
// compatibility tag, and each nonzero canonical combining class (field 3), in ranges. The runtime
// (unicode-nfkd.ts) applies them recursively, decomposes Hangul syllables by the standard's
// arithmetic and puts combining marks in canonical order.
//
//   node tooling/generate-unicode-nfkd.mjs           writes the module
//   node tooling/generate-unicode-nfkd.mjs --check   fails if the module differs from the data
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { gunzipSync } from "node:zlib";
import { isMainScript } from "./run-script.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
export const UNICODE_VERSION = "18.0.0";
const DATA = "test/fixtures/unicode18/UnicodeData.txt.gz";
/** The published UnicodeData.txt of 18.0.0, uncompressed (test/fixtures/unicode18/SHA256SUMS). */
const DATA_SHA256 = "0736451de439ae7baf1425136617da495e09ee5afbe6e394374db7009ea08950";
export const NFKD_MODULE = "packages/crypto-core/src/unicode-nfkd-data.ts";
/** Entries a line of the module holds, so that its lines stay short enough to read. */
const PER_LINE = 8;

/** UnicodeData.txt of 18.0.0, checked against its published SHA-256. */
export function unicodeData(root = ROOT) {
  const bytes = gunzipSync(readFileSync(resolve(root, DATA)));
  const digest = createHash("sha256").update(bytes).digest("hex");
  if (digest !== DATA_SHA256) throw new Error(`${DATA} is not UnicodeData.txt of 18.0.0.`);
  return bytes.toString("utf8");
}

/** The two tables, as the strings the module holds. */
export function nfkdTables(text) {
  const decompositions = [];
  const classes = [];
  for (const line of text.split("\n")) {
    if (line === "") continue;
    const fields = line.split(";");
    const code = fields[0];
    const mapping = fields[5].replace(/^<[a-zA-Z]+> /u, "");
    if (mapping !== "") decompositions.push(`${code}>${mapping}`);
    const value = Number(fields[3]);
    if (value === 0) continue;
    const point = Number.parseInt(code, 16);
    const last = classes.at(-1);
    // A range of code points with one class, as the class runs of combining marks are.
    if (last !== undefined && last.value === value && last.to === point - 1) last.to = point;
    else classes.push({ from: point, to: point, value });
  }
  const hex = (point) => point.toString(16).toUpperCase().padStart(4, "0");
  return {
    decompositions,
    classes: classes.map(({ from, to, value }) =>
      from === to ? `${hex(from)}:${value}` : `${hex(from)}-${hex(to)}:${value}`,
    ),
  };
}

/** A table as a TypeScript string constant: entries joined by ";", eight a line. */
function constant(entries) {
  const lines = [];
  for (let at = 0; at < entries.length; at += PER_LINE)
    lines.push(JSON.stringify(`${entries.slice(at, at + PER_LINE).join(";")};`));
  return lines.join(" +\n  ");
}

/** The module's text. */
export function nfkdModule(root = ROOT) {
  const { decompositions, classes } = nfkdTables(unicodeData(root));
  return `// Generated by tooling/generate-unicode-nfkd.mjs from UnicodeData.txt of Unicode ${UNICODE_VERSION}
// (SHA-256 ${DATA_SHA256}). Do not edit.
// © 2026 Unicode®, Inc. Unicode License v3: https://www.unicode.org/license.txt.

/** The Unicode version of the tables. */
export const UNICODE_VERSION = ${JSON.stringify(UNICODE_VERSION)};

/**
 * Every decomposition mapping of UnicodeData (field 5), its compatibility tag dropped: "code>parts;",
 * code points in hexadecimal. Hangul syllables decompose by arithmetic and are not listed.
 */
export const DECOMPOSITIONS =
  ${constant(decompositions)};

/** Every nonzero canonical combining class (field 3): "first-last:class;" or "code:class;". */
export const COMBINING_CLASSES =
  ${constant(classes)};
`;
}

if (isMainScript(import.meta.url)) {
  const text = nfkdModule();
  const path = resolve(ROOT, NFKD_MODULE);
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== text)
      throw new Error(`${NFKD_MODULE} differs from Unicode ${UNICODE_VERSION}'s data.`);
    console.log(`${NFKD_MODULE} matches UnicodeData.txt of Unicode ${UNICODE_VERSION}.`);
  } else {
    writeFileSync(path, text);
    console.log(`Wrote ${NFKD_MODULE} from Unicode ${UNICODE_VERSION}.`);
  }
}
