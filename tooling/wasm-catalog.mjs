import { cpSync, mkdirSync, readFileSync, readdirSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { WASM_CATALOG } from "./wasm-modules.mjs";
import { resolveRustToolchain } from "./rust-toolchain.mjs";
import { isMainScript } from "./run-script.mjs";

/** Archives only first-party generated modules; MHFE is a separately pinned vendored package. */
export class WasmArchive {
  #root;
  #catalog;

  constructor(root, catalog = WASM_CATALOG) {
    this.#root = root;
    this.#catalog = catalog;
  }

  snapshot(destination) {
    mkdirSync(destination, { recursive: true });
    for (const module of this.#catalog.firstParty())
      cpSync(
        resolve(this.#root, module.generatedDirectory),
        resolve(destination, module.archiveDirectory),
        { recursive: true },
      );
    cpSync(
      resolve(this.#root, "tooling/wasm-canonical-manifest.json"),
      resolve(destination, "wasm-canonical-manifest.json"),
    );
  }

  verify(snapshot) {
    for (const module of this.#catalog.firstParty()) {
      const before = resolve(snapshot, module.archiveDirectory);
      const after = resolve(this.#root, module.generatedDirectory);
      const files = (directory) => readdirSync(directory, { recursive: true }).sort();
      const names = files(before);
      if (JSON.stringify(names) !== JSON.stringify(files(after)))
        throw new Error(
          `${module.label} generated membership differs from the committed snapshot.`,
        );
      for (const name of names)
        if (!readFileSync(resolve(before, name)).equals(readFileSync(resolve(after, name))))
          throw new Error(`${module.label} generated bytes differ for ${name}.`);
    }
    if (
      !readFileSync(resolve(snapshot, "wasm-canonical-manifest.json")).equals(
        readFileSync(resolve(this.#root, "tooling/wasm-canonical-manifest.json")),
      )
    )
      throw new Error("Canonical WASM manifest differs from the committed snapshot.");
  }
}

if (isMainScript(import.meta.url)) {
  const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
  const [operation, path] = process.argv.slice(2);
  if (operation === "audit") console.log(JSON.stringify(WASM_CATALOG.rustsecMatrix()));
  else if (operation === "fetch") {
    // Audit/snapshot need only Node built-ins, including before pnpm dependencies are installed.
    const { runTool } = await import("./wasm-build.mjs");
    const { cargo, environment } = resolveRustToolchain(root);
    for (const { manifestPath } of WASM_CATALOG.nativeCrates())
      runTool(
        cargo,
        ["fetch", "--manifest-path", resolve(root, manifestPath), "--locked"],
        environment,
      );
  } else if ((operation === "snapshot" || operation === "verify") && path !== undefined) {
    const archive = new WasmArchive(root);
    if (operation === "snapshot") archive.snapshot(resolve(path));
    else archive.verify(resolve(path));
  } else throw new Error("Usage: wasm-catalog.mjs audit|fetch|snapshot PATH|verify PATH");
}
