/** Transport and quorum refusals before every command; no engine, randomness or host is used. */
export function checkSskrTransportStartup(): void {
  expectSame(
    urToBytewords(sskrVector.shares[0]),
    sskrVector.firstShareBytewords,
    "SSKR published Bytewords",
  );
  // Every Byteword has four letters: run together they read as written apart (owner, 2026-10-13).
  expectSame(
    bytewordsToUr(sskrVector.firstShareBytewords.replaceAll(" ", "")),
    sskrVector.shares[0],
    "SSKR Bytewords run together",
  );
  expectSame(validateShareSet(sskrVector.shares).length, 5, "SSKR official grouped quorum");
  for (const [name, shares] of [
    ["SSKR one complete group", sskrVector.shares.slice(0, 2)],
    ["SSKR underfilled second group", sskrVector.shares.slice(0, -1)],
  ] as const)
    expectRefused(() => validateShareSet(shares), /groups|threshold/u, name);
  expectRefused(
    () => validateShareSet([...sskrVector.shares, sskrVector.shares[0]]),
    /same SSKR member/u,
    "SSKR duplicate member",
  );
  expectRefused(
    () => validateShareSet([sskrVector.shares[0], sskrSetVector.shares[0]]),
    /different sets/u,
    "SSKR mixed sets",
  );
  // ae is a valid Bytewords pair, but replacing the published checksum's last pair damages it.
  expectRefused(
    () => normalizeShare(`${sskrVector.shares[0].slice(0, -2)}ae`),
    /checksum/u,
    "SSKR damaged transport checksum",
  );
}

/** A public share with one value byte changed and a correct transport CRC, for a digest refusal. */
function changedShareValue(): string {
  const bytes = urToTransport(sskrVector.shares[0]);
  try {
    // Byte 8 is inside the value of this fixed official share, past its framing and metadata.
    bytes[8] = defined(bytes[8]) ^ 1;
    new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength).setUint32(
      bytes.length - CHECKSUM_BYTES,
      crc32(bytes.subarray(0, -CHECKSUM_BYTES)),
    );
    return transportToUr(bytes);
  } finally {
    bytes.fill(0);
  }
}

/** The host's restoring of `shares` compared with `entropy`; `name` names the check. */
async function expectRestored(
  platform: SharePlatform,
  shares: readonly string[],
  entropy: string,
  name: string,
): Promise<void> {
  const restored = await platform.combineShares(shares);
  try {
    if (hexOfBytes(restored) !== entropy)
      throw ERRORS.create("self-test-failed-no-secret-was-processed", [`${name}`]);
  } finally {
    restored.fill(0);
  }
}

/**
 * Compares the colour transport and the host's SSKR library with the known answers; throws, before
 * any secret is touched, at the first difference.
 */
export async function checkSskrKnownAnswers(platform: SharePlatform): Promise<void> {
  checkSskrTransportStartup();
  if (
    shareToColors(sskrVector.shares[0]).join(" ") !== sskrVector.firstShareColors.join(" ") ||
    colorsToShare(sskrVector.firstShareColors.join(" ")) !== sskrVector.shares[0]
  ) {
    throw ERRORS.create("sskr-color-known-answer-self-test-failed-no", []);
  }
  for (const share of sskrVector.shares) {
    if (colorsToShare(shareToColors(share).join("")) !== normalizeShare(share))
      throw ERRORS.create("sskr-color-self-test-failed-no-secret-was", []);
  }
  await expectRestored(platform, sskrVector.shares, sskrVector.entropy, "SSKR recovery");
  await expectRestored(
    platform,
    sskrLongVector.shares,
    sskrLongVector.entropy,
    "SSKR 32-byte recovery",
  );
  const secret = bytesOfHex(sskrSetVector.entropy);
  const seed = bytesOfHex(sskrSetVector.testOnlySeed);
  try {
    const created = await platform.createShares(secret, 2, 3, seed);
    expectSame(created.join("\n"), sskrSetVector.shares.join("\n"), "SSKR creation known answer");
  } finally {
    secret.fill(0);
    seed.fill(0);
  }
  for (const [name, shares] of [
    ["SSKR engine incomplete quorum", sskrVector.shares.slice(0, -1)],
    ["SSKR engine damaged value", [changedShareValue(), ...sskrVector.shares.slice(1)]],
  ] as const)
    await expectRefusedLater(
      async () => {
        const unexpected = await platform.combineShares(shares);
        unexpected.fill(0);
      },
      // Hosts word engine errors differently; the successful official control ran above.
      /.+/u,
      name,
    );
}
